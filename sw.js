self.addEventListener('install', event => {
  event.waitUntil((async () => {
    // A byte-only change (e.g. CRLF checkout) can install the same content release again.
    // Keep its complete cache: failed network preparation must not delete a live copy.
    if ((await shellStatus()).complete) return;
    try { await prepareShell(); }
    catch (error) { await caches.delete(cacheName); throw error; }
  })());
  // No skipWaiting: retain the running release until every old app window closes.
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(name => name.startsWith(prefix) && name !== cacheName).map(name => caches.delete(name)));
    // No clients.claim: never switch a running page to different code underneath it.
  })());
});

self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== new URL(base).origin) return;
  url.search = ''; url.hash = '';
  const key = url.href === base ? indexURL : url.href;
  if (!assets.has(key)) return; // No maps, personal files or arbitrary runtime caching.
  event.respondWith((async () => {
    if (event.request.mode === 'navigate' && !(await shellStatus()).complete) return recoveryPage();
    const cached = await (await caches.open(cacheName)).match(key);
    if (cached) return cached;
    // Fetching a newer unverified module here could mix releases. Fail visibly instead.
    return new Response('アプリのキャッシュが見つかりません。オンラインで開き直し、オフライン準備を再試行してください。入力済みデータの削除は不要です。',
      { status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
  })());
});

self.addEventListener('message', event => {
  if (!event.ports[0] || !['SHELL_STATUS', 'REPAIR_SHELL'].includes(event.data?.type)) return;
  event.waitUntil((async () => {
    try {
      if (event.data.type === 'REPAIR_SHELL') await prepareShell();
      event.ports[0].postMessage(await shellStatus());
    } catch { event.ports[0].postMessage({ release: SHELL.release, complete: false, failed: true }); }
  })());
});
