async function verifiedResponse(url, asset) {
  const response = await fetch(new Request(url, { cache: 'reload', credentials: 'same-origin', redirect: 'error' }));
  if (!response.ok || response.type === 'opaque') throw new Error('App file unavailable');
  const bytes = asset.text
    ? new TextEncoder().encode((await response.clone().text()).replace(/\r\n/g, '\n'))
    : await response.clone().arrayBuffer();
  const hash = [...new Uint8Array(await crypto.subtle.digest('SHA-256', bytes))].map(byte => byte.toString(16).padStart(2, '0')).join('');
  if (hash !== asset.sha256) throw new Error('App release does not match its manifest');
  return response;
}

function prepareShell() {
  if (preparing) return preparing;
  preparing = (async () => {
    // Verify the entire release before writing. A partial deployment cannot mix versions.
    const responses = await Promise.all([...assets].map(async ([url, asset]) => [url, await verifiedResponse(url, asset)]));
    const cache = await caches.open(cacheName);
    const writes = await Promise.allSettled(responses.map(([url, response]) => cache.put(url, response)));
    if (writes.some(result => result.status === 'rejected')) throw new Error('App cache could not be saved');
    if (!(await shellStatus()).complete) throw new Error('App cache is incomplete');
  })().finally(() => { preparing = undefined; });
  return preparing;
}

async function shellStatus() {
  const cache = await caches.open(cacheName);
  const present = await Promise.all([...assets.keys()].map(url => cache.match(url)));
  return { release: SHELL.release, complete: assets.size > 0 && present.every(Boolean) };
}

